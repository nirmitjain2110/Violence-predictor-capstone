import cv2, shutil
from pathlib import Path
from tqdm import tqdm
import random

NUM_FRAMES = 16
IMG_SIZE = 112

def extract(video_path, out_dir, num_frames=NUM_FRAMES, size=IMG_SIZE):
    cap = cv2.VideoCapture(str(video_path))
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if total <= 0:
        cap.release()
        return False
    idxs = set(int(i * total / num_frames) for i in range(num_frames))
    out_dir.mkdir(parents=True, exist_ok=True)
    saved = 0
    for i in range(total):
        ret, frame = cap.read()
        if not ret:
            break
        if i in idxs:
            frame = cv2.resize(frame, (size, size))
            cv2.imwrite(str(out_dir / f"{saved:02d}.jpg"), frame)
            saved += 1
    cap.release()
    return saved == num_frames

def process_dataset(video_label_pairs, frames_root, desc):
    """video_label_pairs: list of (video_path, split, label) tuples"""
    ok, fail = 0, 0
    for v, split, label in tqdm(video_label_pairs, desc=desc):
        out = Path(frames_root) / split / label / v.stem
        if extract(v, out):
            ok += 1
        else:
            fail += 1
    print(f"{desc}: {ok} ok, {fail} failed")

def process_rwf(raw_dir, frames_root):
    raw_dir = Path(raw_dir)
    pairs = []
    for split in ["train", "val"]:
        for src_name, label in [("Fight", "Violence"), ("NonFight", "NonViolence")]:
            src = raw_dir / split / src_name
            if not src.exists():
                print(f"MISSING: {src}")
                continue
            for v in list(src.glob("*.avi")) + list(src.glob("*.mp4")):
                pairs.append((v, split, label))
    process_dataset(pairs, frames_root, "RWF-2000")

def process_rlvs(raw_dir, frames_root, val_frac=0.2, seed=42):
    raw_dir = Path(raw_dir)
    pairs = []
    for src_name, label in [("Violence", "Violence"), ("NonViolence", "NonViolence")]:
        src = raw_dir / src_name
        if not src.exists():
            print(f"MISSING: {src}")
            continue
        videos = list(src.glob("*.mp4")) + list(src.glob("*.avi"))
        rng = random.Random(seed)
        rng.shuffle(videos)
        n_val = int(len(videos) * val_frac)
        val_videos = set(videos[:n_val])
        for v in videos:
            split = "val" if v in val_videos else "train"
            pairs.append((v, split, label))
    process_dataset(pairs, frames_root, "RLVS")

